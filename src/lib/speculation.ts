/*
 * Speculation Rules — правило предзагрузки внутренних страниц.
 *
 * Наведение на внутреннюю ссылку заранее рендерит страницу в скрытой вкладке,
 * клик её просто активирует: переход по каталогу становится мгновенным, а в поле
 * LCP такой навигации Chrome считает от активации — то есть почти нулевым.
 *
 * Правило вставлено руками (а не флагом experimental.clientPrerender): так у нас
 * полный контроль над eagerness и списком исключений.
 *
 * Границы применимости, приняты сознательно: работают Chrome и Edge (~75 % трафика),
 * Firefox правило игнорирует, Safari 26 умеет только prefetch и только за префом.
 * Для них поведение сайта прежнее — правило безопасно неактивно.
 *
 * ВАЖНО при подключении аналитики: пререндер выполняет скрипты страницы. GA4 сам
 * откладывает отправку до активации, Яндекс.Метрика — нет, ей нужна проверка
 * document.prerendering и событие prerenderingchange, иначе в отчётах появятся
 * просмотры страниц, которые никто не открывал.
 *
 * ВАЖНО при включении CSP: инлайновое правило требует 'inline-speculation-rules'
 * в script-src (см. заготовку заголовка в public/.htaccess).
 */

/** Адреса, которые предзагружать не нужно */
const EXCLUDED = [
  /* Страница заявки: переход на неё всегда осознанный, наведение на кнопку
     «Рассчитать стоимость» происходит и без намерения нажать */
  '/order/',
  /* Не документы: карта сайта, robots и прочие файлы в предзагрузке бессмысленны */
  '/*.xml',
  '/*.txt',
  '/*.json',
  '/*.webmanifest',
];

/**
 * eagerness: 'moderate' — предзагрузка после ~200 мс наведения или на pointerdown.
 * Chrome держит в очереди не более двух таких страниц (FIFO), поэтому лишнего
 * трафика правило не создаёт даже при быстром переборе ссылок мышью.
 *
 * Относительные шаблоны в href_matches разрешаются относительно документа, то есть
 * правило по построению касается только своего домена — внешние ссылки не попадают.
 */
export const speculationRules = {
  prerender: [
    {
      where: {
        and: [{ href_matches: '/*' }, { not: { href_matches: EXCLUDED } }],
      },
      eagerness: 'moderate',
    },
  ],
};
